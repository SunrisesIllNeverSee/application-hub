// Relocate, backup/restore, rekey, plaintext export consent, application
// extraction, retract, resolve --keep both, passphrase never persisted.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { extractApplication } from '../src/extract.mjs'
import { ACCOUNT, MARK, PASS, VAULT, allBytes, buildVault, initWorkspace, loadApp, mutateEnvelope, readManifest, run, scratch, writeFile } from './helpers.mjs'

async function populated(label) {
  const v = await buildVault()
  const dir = scratch(label)
  const root = await initWorkspace(dir)
  const r = await run(['import-backup', writeFile(dir, 'b.json', v.envelope), '--workspace', root, '--account', ACCOUNT, '--yes'])
  assert.equal(r.code, 0, r.err)
  return { v, dir, root }
}

test('plaintext export: needs --plaintext, prints an exposure warning, refuses without confirmation, never overwrites', async () => {
  const { v, dir, root } = await populated('plain')
  const outDir = path.join(dir, 'plain-out')
  let r = await run(['export', 'all', '--out', outDir, '--workspace', root, '--yes'])
  assert.equal(r.code, 2)
  assert.match(r.err, /needs --plaintext/)
  r = await run(['export', '--plaintext', 'all', '--out', outDir, '--workspace', root])
  assert.equal(r.code, 3, 'no confirmation on a non-terminal -> refused')
  assert.match(r.err, /PLAINTEXT EXPORT WARNING/)
  assert.equal(fs.existsSync(outDir), false)
  r = await run(['export', '--plaintext', 'all', '--out', outDir, '--workspace', root, '--yes'])
  assert.equal(r.code, 0, r.err)
  assert.match(r.err, /UNENCRYPTED/)
  const files = fs.readdirSync(outDir)
  assert.ok(files.includes('INDEX.md'))
  const versionMd = files.find((f) => f.startsWith('version-'))
  const md = fs.readFileSync(path.join(outDir, versionMd), 'utf8')
  assert.ok(md.includes(MARK))
  assert.match(md, /^---\nid: "version:/)
  assert.match(md, /exposure: plaintext export/)
  // a non-empty target is refused
  r = await run(['export', '--plaintext', v.version.id, '--out', outDir, '--workspace', root, '--yes'])
  assert.equal(r.code, 2)
  // inside the workspace only exports/ is allowed
  r = await run(['export', '--plaintext', v.version.id, '--out', path.join(root, 'answers', 'x'), '--workspace', root, '--yes'])
  assert.equal(r.code, 2)
  r = await run(['export', '--plaintext', v.version.id, '--out', path.join(root, 'exports', 'one'), '--workspace', root, '--yes'])
  assert.equal(r.code, 0, r.err)
  const audit = fs.readFileSync(path.join(root, 'audit/companion.jsonl'), 'utf8')
  assert.match(audit, /"op":"plaintext_export"/)
  assert.equal(audit.includes(MARK), false)
})

test('relocate copies + verifies, leaves the original in place, and records the move in both', async () => {
  const { root } = await populated('reloc')
  const dest = scratch('reloc-dest')
  let r = await run(['relocate', dest, '--workspace', root])
  assert.equal(r.code, 3)
  assert.equal(fs.existsSync(path.join(dest, 'AQUA')), false)
  r = await run(['relocate', path.join(root, 'exports'), '--workspace', root, '--yes'])
  assert.equal(r.code, 2, 'cannot relocate into itself')
  r = await run(['relocate', dest, '--workspace', root, '--yes'])
  assert.equal(r.code, 0, r.err)
  const newRoot = path.join(dest, 'AQUA')
  assert.equal((await run(['verify', '--workspace', newRoot])).code, 0)
  assert.equal((await run(['verify', '--workspace', root])).code, 0, 'original still intact')
  assert.equal(readManifest(newRoot).relocated_from.path, root)
  assert.equal(readManifest(root).relocated_to.path, newRoot)
  assert.equal(readManifest(newRoot).workspace_id, readManifest(root).workspace_id)
  const st = await run(['status', '--workspace', root])
  assert.match(st.err, /was copied to/)
  r = await run(['relocate', dest, '--workspace', root, '--yes'])
  assert.equal(r.code, 2, 'refuses a destination that already holds a workspace')
})

test('backup -> restore-workspace round trip; wrong passphrase refused; never overwrites', async () => {
  const { dir, root } = await populated('backup')
  const out = path.join(dir, 'ws-backup.aqua')
  let r = await run(['backup', path.join(root, 'exports', 'b.aqua'), '--workspace', root, '--yes'])
  assert.equal(r.code, 2, 'backup must go outside the workspace')
  r = await run(['backup', out, '--workspace', root, '--yes'])
  assert.equal(r.code, 0, r.err)
  const text = fs.readFileSync(out, 'utf8')
  assert.equal(text.includes(MARK), false)
  assert.equal(text.includes('Synthetic Program'), false, 'even public files are inside the encrypted bundle')
  r = await run(['backup', out, '--workspace', root, '--yes'])
  assert.equal(r.code, 2, 'refuses to overwrite')
  const target = scratch('restore-target')
  r = await run(['restore-workspace', out, '--path', target, '--yes'], { env: { AQUA_PASSPHRASE: 'wrong-passphrase-x' } })
  assert.notEqual(r.code, 0)
  assert.equal(fs.existsSync(path.join(target, 'AQUA', 'workspace.json')), false)
  r = await run(['restore-workspace', out, '--path', target, '--yes'])
  assert.equal(r.code, 0, r.err)
  const restored = path.join(target, 'AQUA')
  assert.equal((await run(['verify', '--workspace', restored])).code, 0)
  assert.deepEqual(Object.keys(readManifest(restored).records).sort(), Object.keys(readManifest(root).records).sort())
  r = await run(['restore-workspace', out, '--path', target, '--yes'])
  assert.equal(r.code, 2, 'refuses an existing workspace')
})

test('rekey re-encrypts everything; the old passphrase stops working; an interrupted rekey is finished by re-running', async () => {
  const { v, dir, root } = await populated('rekey')
  const NEW = 'synthetic-new-passphrase-55'
  let r = await run(['rekey', '--workspace', root, '--yes'], { env: { AQUA_NEW_PASSPHRASE: NEW } })
  assert.equal(r.code, 0, r.err)
  assert.equal((await run(['verify', '--workspace', root])).code, 4, 'old passphrase refused')
  const ok = await run(['verify', '--workspace', root], { env: { AQUA_PASSPHRASE: NEW } })
  assert.equal(ok.code, 0, ok.out)
  const shown = await run(['show', v.version.id, '--reveal', '--workspace', root], { env: { AQUA_PASSPHRASE: NEW } })
  assert.ok(shown.out.includes(MARK))
  // account binding still works after rekey
  r = await run(['import-backup', path.join(dir, 'b.json'), '--workspace', root, '--account', 'other@example.invalid', '--yes'], { env: { AQUA_PASSPHRASE: NEW } })
  assert.equal(r.code, 5)
  // interrupted rekey: pending_rekey present and some files already under the new key
  const NEWER = 'synthetic-newer-passphrase-66'
  const m = readManifest(root)
  const { deriveWorkspaceKeys, encryptWithKeys, newSaltB64, macHex, canonicalJson } = await import('../src/crypto.mjs')
  const oldKeys = await deriveWorkspaceKeys(NEW, m.kdf.salt_b64, m.kdf.iters)
  const salt = newSaltB64()
  const newKeys = await deriveWorkspaceKeys(NEWER, salt)
  m.pending_rekey = { kdf: { alg: 'PBKDF2-SHA256', iters: 210000, salt_b64: salt }, key_check: await encryptWithKeys(newKeys, `aqua-companion-key-check:v1:${m.workspace_id}`), started_at: new Date().toISOString() }
  // re-encrypt ONE file under the new key as if the process died afterwards
  const [, e] = Object.entries(m.records).find(([, x]) => x.kind === 'version')
  const rec = JSON.parse(fs.readFileSync(path.join(root, e.path), 'utf8'))
  const { decryptWithKeys, sha256Hex } = await import('../src/crypto.mjs')
  const { recordAad } = await import('../src/workspace.mjs')
  const plain = await decryptWithKeys(oldKeys, rec.enc, recordAad(rec))
  const { sha256: _s, ...head } = rec
  head.enc = await encryptWithKeys(newKeys, plain, recordAad(rec))
  head.sha256 = await sha256Hex(canonicalJson(head))
  fs.writeFileSync(path.join(root, e.path), JSON.stringify(head))
  const { manifest_mac: _mm, ...rest } = m
  m.manifest_mac = await macHex(oldKeys, canonicalJson(rest))
  fs.writeFileSync(path.join(root, 'workspace.json'), JSON.stringify(m))
  r = await run(['status', '--workspace', root])
  assert.match(r.out, /interrupted/)
  r = await run(['show', v.version.id, '--reveal', '--workspace', root], { env: { AQUA_PASSPHRASE: NEW } })
  assert.equal(r.code, 4, 'normal use blocked until the rekey is finished')
  r = await run(['rekey', '--workspace', root, '--yes'], { env: { AQUA_PASSPHRASE: NEW, AQUA_NEW_PASSPHRASE: 'not-the-pending-one' } })
  assert.equal(r.code, 2)
  r = await run(['rekey', '--workspace', root, '--yes'], { env: { AQUA_PASSPHRASE: NEW, AQUA_NEW_PASSPHRASE: NEWER } })
  assert.equal(r.code, 0, r.err)
  const fin = await run(['verify', '--workspace', root], { env: { AQUA_PASSPHRASE: NEWER } })
  assert.equal(fin.code, 0, fin.out + fin.err)
})

test('passphrase and vault secret are never written into the workspace or its exports', async () => {
  const { v, dir, root } = await populated('nopass')
  await run(['add-evidence', '--title', 'synthetic', '--workspace', root, '--yes'])
  await run(['comment', '--version', v.version.id, '--body-file', writeFile(dir, 'c.txt', 'synthetic comment'), '--workspace', root, '--yes'])
  await run(['export-backup', path.join(root, 'exports', 'for-browser.json'), '--workspace', root, '--yes'])
  await run(['backup', path.join(dir, 'ws.aqua'), '--workspace', root, '--yes'])
  await run(['show', v.version.id, '--reveal', '--workspace', root])
  await run(['verify', '--workspace', root])
  const bytes = Buffer.concat([allBytes(root), fs.readFileSync(path.join(dir, 'ws.aqua'))])
  for (const secret of [PASS, VAULT]) {
    assert.equal(bytes.includes(secret), false)
    assert.equal(bytes.includes(Buffer.from(secret).toString('base64')), false)
    assert.equal(bytes.includes(Buffer.from(secret).toString('hex')), false)
  }
  assert.equal(bytes.includes(ACCOUNT), false)
})

test('import-application: txt / md / json / html extraction keeps exact wording; unsupported or empty files are refused', async () => {
  const md = extractApplication('a.md', '# Title A\n\nOrg: Example Org\n\n1. What problem do you solve?  (100 words)\n2) Who are your users?\n- Describe traction (300 characters)\n\nSome prose line.\n')
  assert.equal(md.title, 'Title A')
  assert.equal(md.org, 'Example Org')
  assert.deepEqual(md.questions.map((q) => q.text), ['What problem do you solve?  (100 words)', 'Who are your users?', 'Describe traction (300 characters)'])
  assert.equal(md.questions[0].word_limit, 100)
  assert.equal(md.questions[2].char_limit, 300)
  const txt = extractApplication('b.txt', 'Synthetic Form\nWhy do you want to join?\nTell us about a failure? *\n')
  assert.equal(txt.title, 'Synthetic Form')
  assert.equal(txt.questions[1].required, true)
  const json = extractApplication('c.json', JSON.stringify({ title: 'J', organization: 'O', questions: ['Q one?', { prompt: 'Q two', max_words: 50, required: true }] }))
  assert.deepEqual(json.questions.map((q) => [q.text, q.word_limit, q.required]), [['Q one?', null, false], ['Q two', 50, true]])
  const html = extractApplication('d.html', '<html><head><title>Ignored</title><script>alert("x?")</script></head><body><h1>Synthetic &amp; Co Grant</h1><label>What&#39;s your plan? (250 words)</label><ol><li>Budget breakdown (1000 characters)</li></ol><p>Thanks.</p></body></html>')
  assert.equal(html.title, 'Synthetic & Co Grant')
  assert.deepEqual(html.questions.map((q) => q.text), ["What's your plan? (250 words)", 'Budget breakdown (1000 characters)'])
  assert.throws(() => extractApplication('e.pdf', 'x'), /unsupported file type/)
  assert.throws(() => extractApplication('f.txt', 'Just a title\nand prose.'), /no questions/)

  const dir = scratch('import-app')
  const root = await initWorkspace(dir)
  const f = writeFile(dir, 'form.html', '<h1>Synthetic Accelerator</h1><p>1. What are you building? (50 words)</p>')
  let r = await run(['import-application', f, '--workspace', root])
  assert.equal(r.code, 3, 'consent first')
  assert.match(r.out, /What are you building\? \(50 words\)/, 'extraction shown for review before consent')
  r = await run(['import-application', f, '--workspace', root, '--yes'])
  assert.equal(r.code, 0, r.err)
  const m = readManifest(root)
  const src = Object.entries(m.records).find(([, e]) => e.kind === 'source_document')
  assert.ok(src[1].path.startsWith('applications/queued/sources/'))
  const shown = JSON.parse((await run(['show', src[0], '--reveal', '--json', '--workspace', root])).out)
  assert.equal(shown.data.text, fs.readFileSync(f, 'utf8'), 'original document kept byte-for-byte (encrypted)')
  r = await run(['import-application', writeFile(dir, 'x.bin', Buffer.from([0, 1, 2, 3])), '--workspace', root, '--yes'])
  assert.equal(r.code, 2)
})

test('retract tombstones a staged record (file kept, not exported); projections cannot be retracted', async () => {
  const { v, dir, root } = await populated('retract')
  await run(['add-evidence', '--title', 'synthetic', '--workspace', root, '--yes'])
  const [k, e] = Object.entries(readManifest(root).records).find(([, x]) => x.kind === 'evidence' && x.authority === 'staging')
  let r = await run(['retract', k, '--workspace', root, '--yes'])
  assert.equal(r.code, 0, r.err)
  const m = readManifest(root)
  assert.equal(m.records[k].status, 'tombstoned')
  assert.ok(fs.existsSync(path.join(root, e.path)))
  r = await run(['export-backup', path.join(dir, 'x.json'), '--workspace', root, '--yes'])
  assert.match(r.out, /Nothing to export/)
  r = await run(['retract', v.version.id, '--workspace', root, '--yes'])
  assert.equal(r.code, 2)
  assert.match(r.err, /browser/)
})

test('resolve --keep both forks a staged record under a new id and archives the original', async () => {
  const { v, dir, root } = await populated('both')
  const app = await loadApp()
  await run(['add-evidence', '--title', 'synthetic staged evidence', '--workspace', root, '--yes'])
  const out = path.join(dir, 'e.json')
  assert.equal((await run(['export-backup', out, '--workspace', root, '--yes'])).code, 0)
  await app.importVault(v.storage, VAULT, fs.readFileSync(out, 'utf8'))
  const [evKey] = Object.entries(readManifest(root).records).find(([, x]) => x.kind === 'evidence' && x.authority === 'staging')
  const evId = evKey.slice('evidence:'.length)
  // the browser links the restored evidence to a version: the vault copy now differs
  await app.linkEvidence(v.storage, evId, { target_kind: 'version', target_id: v.version.id })
  const env = await app.exportVault(v.storage, VAULT)
  let r = await run(['import-backup', writeFile(dir, 'after.json', env), '--workspace', root, '--account', ACCOUNT, '--yes'])
  assert.equal(r.code, 0, r.err)
  const [conflict] = JSON.parse((await run(['conflicts', '--json', '--workspace', root])).out)
  assert.equal(conflict.record_id, evKey)
  r = await run(['resolve', conflict.conflict_id, '--keep', 'both', '--workspace', root, '--yes'])
  assert.equal(r.code, 0, r.err)
  const m = readManifest(root)
  assert.equal(m.records[evKey].authority, 'projection')
  const fork = Object.entries(m.records).find(([, x]) => x.variant_of === evKey)
  assert.ok(fork && fork[1].authority === 'staging' && fork[0] !== evKey)
  assert.ok(Object.keys(m.records).some((x) => x.startsWith(`${evKey}#archived-`)))
  assert.equal((await run(['verify', '--workspace', root])).code, 0)
  void mutateEnvelope
})
