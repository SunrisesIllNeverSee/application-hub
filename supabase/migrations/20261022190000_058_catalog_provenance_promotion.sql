CREATE OR REPLACE FUNCTION public.guard_catalog_candidate_events()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_state        public.catalog_candidate_state;
  v_submitter    uuid;
  v_checks       jsonb;
  v_published_rev uuid;
BEGIN
  NEW.at := now();
  NEW.tx_id := txid_current();

  SELECT c.state, c.submitted_by, c.checks, c.published_revision_id
    INTO v_state, v_submitter, v_checks, v_published_rev
    FROM public.catalog_candidates c WHERE c.id = NEW.candidate_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'unknown candidate %', NEW.candidate_id USING ERRCODE = '23503';
  END IF;

  IF NEW.from_state IS NULL THEN
    IF NEW.to_state <> 'candidate' OR v_state <> 'candidate'
       OR EXISTS (SELECT 1 FROM public.catalog_candidate_events e WHERE e.candidate_id = NEW.candidate_id) THEN
      RAISE EXCEPTION 'only the first event may have no from_state' USING ERRCODE = '23514';
    END IF;
  ELSE
    IF NEW.from_state <> v_state THEN
      RAISE EXCEPTION 'stale transition: candidate is %, event says %', v_state, NEW.from_state USING ERRCODE = '40001';
    END IF;
    IF NOT public.catalog_transition_allowed(NEW.from_state, NEW.to_state) THEN
      RAISE EXCEPTION 'illegal catalog transition % -> %', NEW.from_state, NEW.to_state USING ERRCODE = '23514';
    END IF;
  END IF;

  -- who may perform which step
  IF NEW.actor_role = 'curator'
     AND (NEW.actor IS NULL OR NOT EXISTS (SELECT 1 FROM public.catalog_curators k WHERE k.user_id = NEW.actor)) THEN
    RAISE EXCEPTION 'curator events require a catalog curator actor' USING ERRCODE = '42501';
  END IF;
  IF NEW.actor_role = 'submitter' AND NEW.actor IS DISTINCT FROM v_submitter THEN
    RAISE EXCEPTION 'submitter events must be made by the submitter' USING ERRCODE = '42501';
  END IF;
  IF NEW.to_state IN ('matched','verified','approved','rejected','published') AND NEW.actor_role <> 'curator' THEN
    RAISE EXCEPTION '% requires a curator', NEW.to_state USING ERRCODE = '42501';
  END IF;
  IF NEW.to_state = 'withdrawn' AND NEW.actor_role <> 'submitter' THEN
    RAISE EXCEPTION 'only the submitter withdraws a candidate' USING ERRCODE = '42501';
  END IF;
  IF NEW.to_state = 'verified'
     AND coalesce(v_checks->>'all_passed', 'false') <> 'true'
     AND NOT (coalesce(NEW.evidence->>'override', 'false') = 'true'
              AND length(btrim(coalesce(NEW.note, ''))) >= 10) THEN
    RAISE EXCEPTION 'verified requires all checks passing or a curator override note' USING ERRCODE = '23514';
  END IF;
  IF NEW.to_state = 'published' AND v_published_rev IS NULL THEN
    RAISE EXCEPTION 'published is recorded only by catalog_publish_candidate' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.catalog_candidate_events_apply()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NEW.from_state IS NOT NULL THEN
    UPDATE public.catalog_candidates SET state = NEW.to_state WHERE id = NEW.candidate_id;
  END IF;
  RETURN NULL;
END;
$$;

