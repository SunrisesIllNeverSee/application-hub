-- ------------------------------------------------------------
-- 13b. Review transition (service_role only, one transaction)
--      Source review signals, program match, payload patch + mapping
--      overrides, checks and the event are written together or not at
--      all. Re-checks the actor and the allowed transition; the event
--      triggers re-check the verified/published rules against the checks
--      written in this same call.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.catalog_transition_candidate(
  candidate_id        uuid,
  to_state            public.catalog_candidate_state,
  actor_id            uuid,
  actor_role          text,
  note                text    DEFAULT NULL,
  checks              jsonb   DEFAULT NULL,
  payload_patch       jsonb   DEFAULT NULL,
  program_match_id    uuid    DEFAULT NULL,
  mappings            jsonb   DEFAULT NULL,
  evidence            jsonb   DEFAULT NULL,
  source_review       jsonb   DEFAULT NULL,
  clear_program_match boolean DEFAULT false)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $fn$
#variable_conflict use_column
DECLARE
  v_cid      uuid := catalog_transition_candidate.candidate_id;
  v_to       public.catalog_candidate_state := catalog_transition_candidate.to_state;
  v_actor    uuid := catalog_transition_candidate.actor_id;
  v_role     text := catalog_transition_candidate.actor_role;
  v_note     text := catalog_transition_candidate.note;
  v_checks   jsonb := catalog_transition_candidate.checks;
  v_patch    jsonb := catalog_transition_candidate.payload_patch;
  v_match    uuid := catalog_transition_candidate.program_match_id;
  v_maps     jsonb := catalog_transition_candidate.mappings;
  v_evidence jsonb := coalesce(catalog_transition_candidate.evidence, '{}'::jsonb);
  v_review   jsonb := catalog_transition_candidate.source_review;
  v_clear    boolean := coalesce(catalog_transition_candidate.clear_program_match, false);
  c          public.catalog_candidates%ROWTYPE;
  v_payload  jsonb;
  v_m        jsonb;
  v_ix       int;
  v_n        int;
  v_tier     text;
  v_self     boolean := false;
  k          text;
BEGIN
  IF NOT public.is_canonical_writer() THEN
    RAISE EXCEPTION 'catalog_transition_candidate is service-side only' USING ERRCODE = '42501';
  END IF;
  IF jsonb_typeof(v_evidence) <> 'object' THEN
    RAISE EXCEPTION 'evidence must be an object' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO c FROM public.catalog_candidates WHERE id = v_cid FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'catalog_transition_candidate: candidate % not found', v_cid USING ERRCODE = 'P0002';
  END IF;
  IF v_role NOT IN ('submitter','curator','system') THEN
    RAISE EXCEPTION 'unknown actor_role %', v_role USING ERRCODE = '22023';
  END IF;
  IF v_role = 'curator'
     AND (v_actor IS NULL OR NOT EXISTS (SELECT 1 FROM public.catalog_curators k2 WHERE k2.user_id = v_actor)) THEN
    RAISE EXCEPTION 'catalog_transition_candidate: actor is not a catalog curator' USING ERRCODE = '42501';
  END IF;
  IF v_to = 'published' THEN
    RAISE EXCEPTION 'publish through catalog_publish_candidate' USING ERRCODE = '42501';
  END IF;
  IF NOT public.catalog_transition_allowed(c.state, v_to) THEN
    RAISE EXCEPTION 'illegal catalog transition % -> %', c.state, v_to USING ERRCODE = '23514';
  END IF;

  -- 1. source review signals (evidence columns stay immutable via trigger)
  IF v_review IS NOT NULL AND v_review <> '{}'::jsonb THEN
    IF jsonb_typeof(v_review) <> 'object' THEN
      RAISE EXCEPTION 'source_review must be an object' USING ERRCODE = '22023';
    END IF;
    FOR k IN SELECT jsonb_object_keys(v_review) LOOP
      IF k NOT IN ('reuse','robots_disallow','verification_status') THEN
        RAISE EXCEPTION 'source_review.% is not reviewable', k USING ERRCODE = '22023';
      END IF;
    END LOOP;
    IF c.source_id IS NULL THEN
      RAISE EXCEPTION 'candidate has no source to review' USING ERRCODE = '23514';
    END IF;
    UPDATE public.catalog_sources s SET
      reuse               = CASE WHEN v_review ? 'reuse' THEN v_review->>'reuse' ELSE s.reuse END,
      robots_disallow     = CASE WHEN v_review ? 'robots_disallow' THEN (v_review->>'robots_disallow')::boolean ELSE s.robots_disallow END,
      verification_status = CASE WHEN v_review ? 'verification_status' THEN v_review->>'verification_status' ELSE s.verification_status END,
      last_checked_at     = now()
    WHERE s.id = c.source_id;
  END IF;

  -- 2. program match (this candidate revises an existing canonical template)
  IF v_clear OR (v_match IS NOT NULL AND v_match IS DISTINCT FROM c.program_match_id) THEN
    IF c.state NOT IN ('candidate','extracted','matched') THEN
      RAISE EXCEPTION 'program match is frozen from verified onward' USING ERRCODE = '42501';
    END IF;
    IF NOT v_clear AND NOT EXISTS (SELECT 1 FROM public.programs p WHERE p.id = v_match AND p.source::text = 'canonical') THEN
      RAISE EXCEPTION 'program_match_id must reference a canonical program' USING ERRCODE = '23514';
    END IF;
    UPDATE public.catalog_candidates SET program_match_id = CASE WHEN v_clear THEN NULL ELSE v_match END WHERE id = c.id;
  END IF;

  -- 3. payload patch (allowlisted top-level keys) + mapping overrides
  v_payload := c.payload;
  IF v_patch IS NOT NULL AND v_patch <> '{}'::jsonb THEN
    IF jsonb_typeof(v_patch) <> 'object' THEN
      RAISE EXCEPTION 'payload_patch must be an object' USING ERRCODE = '22023';
    END IF;
    FOR k IN SELECT jsonb_object_keys(v_patch) LOOP
      IF k NOT IN ('program','entity','cycle','eligibility','requirements','sections','questions','source_refs','evidence') THEN
        RAISE EXCEPTION 'payload_patch.% is not an allowed key', k USING ERRCODE = '22023';
      END IF;
    END LOOP;
    v_payload := v_payload || v_patch;
  END IF;
  IF v_maps IS NOT NULL AND jsonb_typeof(v_maps) = 'array' AND jsonb_array_length(v_maps) > 0 THEN
    v_n := coalesce(jsonb_array_length(v_payload->'questions'), 0);
    FOR v_m IN SELECT x FROM jsonb_array_elements(v_maps) x LOOP
      v_ix := (v_m->>'index')::int;
      IF v_ix IS NULL OR v_ix < 0 OR v_ix >= v_n THEN
        RAISE EXCEPTION 'mapping index % out of range', v_m->>'index' USING ERRCODE = '22023';
      END IF;
      IF coalesce(jsonb_typeof(v_m->'canonical_question_id'), 'null') = 'null' THEN
        v_payload := v_payload #- ARRAY['questions', v_ix::text, 'mapping'];
      ELSE
        IF NOT EXISTS (SELECT 1 FROM public.archived_questions a WHERE a.id = (v_m->>'canonical_question_id')::uuid) THEN
          RAISE EXCEPTION 'canonical question % not found', v_m->>'canonical_question_id' USING ERRCODE = '23503';
        END IF;
        v_tier := coalesce(nullif(v_m->>'tier', 'novel'), 'curator');
        IF v_tier NOT IN ('exact','normalized','semantic','curator') THEN
          RAISE EXCEPTION 'unknown mapping tier %', v_tier USING ERRCODE = '22023';
        END IF;
        v_payload := jsonb_set(v_payload, ARRAY['questions', v_ix::text, 'mapping'],
          jsonb_strip_nulls(jsonb_build_object('canonical_question_id', lower(v_m->>'canonical_question_id'),
                                               'tier', v_tier, 'rationale', left(v_m->>'rationale', 2000))));
      END IF;
    END LOOP;
  ELSIF v_maps IS NOT NULL AND jsonb_typeof(v_maps) <> 'array' THEN
    RAISE EXCEPTION 'mappings must be an array' USING ERRCODE = '22023';
  END IF;
  IF (SELECT count(*) <> count(DISTINCT q->'mapping'->>'canonical_question_id')
        FROM jsonb_array_elements(coalesce(v_payload->'questions', '[]'::jsonb)) q
       WHERE q->'mapping'->>'canonical_question_id' IS NOT NULL) THEN
    RAISE EXCEPTION 'two questions map to the same canonical question' USING ERRCODE = '23505';
  END IF;
  IF v_payload IS DISTINCT FROM c.payload THEN
    UPDATE public.catalog_candidates SET payload = v_payload WHERE id = c.id;  -- frozen-state rule in trigger
  END IF;

  -- 4. checks (read by the verified rule in the event trigger)
  IF v_checks IS NOT NULL THEN
    UPDATE public.catalog_candidates SET checks = v_checks WHERE id = c.id;
  END IF;

  -- 5. the event; self-approval is allowed but recorded
  IF v_to = 'approved' AND v_actor IS NOT NULL AND v_actor = c.submitted_by THEN
    v_self := true;
    v_evidence := v_evidence || jsonb_build_object('self_approved', true);
  END IF;
  INSERT INTO public.catalog_candidate_events (candidate_id, from_state, to_state, actor, actor_role, note, evidence)
  VALUES (c.id, c.state, v_to, v_actor, v_role, v_note, v_evidence);

  RETURN jsonb_build_object('candidate_id', c.id, 'from_state', c.state, 'to_state', v_to,
                            'self_approved', v_self, 'payload_changed', v_payload IS DISTINCT FROM c.payload);
END;
$fn$;

