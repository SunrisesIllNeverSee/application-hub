CREATE TABLE IF NOT EXISTS public.catalog_sources (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  url                 text NOT NULL CHECK (length(url) <= 1000 AND url ~* '^https?://'),
  final_url           text CHECK (final_url IS NULL OR (length(final_url) <= 1000 AND final_url ~* '^https?://')),
  capture_method      text NOT NULL CHECK (capture_method IN ('url_fetch','curator_upload','public_paste','public_file')),
  captured_at         timestamptz NOT NULL DEFAULT now(),
  content_sha256      text CHECK (content_sha256 IS NULL OR content_sha256 ~ '^[0-9a-f]{64}$'),
  reuse               text NOT NULL DEFAULT 'unknown' CHECK (reuse IN ('allowed','unknown','disallowed')),
  robots_disallow     boolean,
  snapshot_text       text CHECK (snapshot_text IS NULL OR length(snapshot_text) <= 200000),
  last_checked_at     timestamptz,
  verification_status text NOT NULL DEFAULT 'unverified'
                      CHECK (verification_status IN ('unverified','verified','stale','failed')),
  created_at          timestamptz NOT NULL DEFAULT now(),
  -- server-side capture (capture_method = 'url_fetch'): when the server
  -- fetched the page and the robots/meta reuse signals it observed.
  fetched_at          timestamptz,
  reuse_signals       text[] NOT NULL DEFAULT '{}' CHECK (cardinality(reuse_signals) <= 50),
  -- digest of snapshot_text as stored (always computed here). For url_fetch,
  -- content_sha256 is the digest of the raw bytes the server received.
  snapshot_sha256     text CHECK (snapshot_sha256 IS NULL OR snapshot_sha256 ~ '^[0-9a-f]{64}$'),
  -- latest curator re-check of the live URL (observed digest/status/signals)
  last_check          jsonb CHECK (last_check IS NULL OR jsonb_typeof(last_check) = 'object'),
  CHECK (capture_method <> 'url_fetch' OR (fetched_at IS NOT NULL AND content_sha256 IS NOT NULL))
);

-- Evidence is immutable once captured; only the review signals move
-- (reuse, robots_disallow, verification_status, last_checked_at, last_check).
-- Client-supplied captures: content_sha256 is recomputed from snapshot_text.
-- url_fetch: content_sha256 is the server-observed raw-content digest.
CREATE OR REPLACE FUNCTION public.guard_catalog_sources()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND (
       NEW.url IS DISTINCT FROM OLD.url
    OR NEW.final_url IS DISTINCT FROM OLD.final_url
    OR NEW.capture_method IS DISTINCT FROM OLD.capture_method
    OR NEW.captured_at IS DISTINCT FROM OLD.captured_at
    OR NEW.snapshot_text IS DISTINCT FROM OLD.snapshot_text
    OR NEW.content_sha256 IS DISTINCT FROM OLD.content_sha256
    OR NEW.created_at IS DISTINCT FROM OLD.created_at
    OR NEW.fetched_at IS DISTINCT FROM OLD.fetched_at
    OR NEW.reuse_signals IS DISTINCT FROM OLD.reuse_signals
    OR NEW.snapshot_sha256 IS DISTINCT FROM OLD.snapshot_sha256
  ) THEN
    RAISE EXCEPTION 'catalog_sources evidence is immutable' USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.capture_method <> 'url_fetch' THEN
      NEW.fetched_at := NULL;
      NEW.reuse_signals := '{}';
      NEW.content_sha256 := CASE WHEN NEW.snapshot_text IS NULL THEN NULL
                                 ELSE encode(sha256(convert_to(NEW.snapshot_text, 'UTF8')), 'hex') END;
    END IF;
    NEW.snapshot_sha256 := CASE WHEN NEW.snapshot_text IS NULL THEN NULL
                                ELSE encode(sha256(convert_to(NEW.snapshot_text, 'UTF8')), 'hex') END;
  END IF;
  RETURN NEW;
END;
$$;

