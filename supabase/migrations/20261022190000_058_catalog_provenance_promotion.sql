-- Mirrors norm() in qaapplication/src/canonical-053-data.mjs and
-- app/lib/catalog-promotion (lowercase ASCII alnum runs).
CREATE OR REPLACE FUNCTION public.catalog_norm(p text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = pg_catalog, pg_temp
AS $$
  SELECT btrim(regexp_replace(lower(coalesce(p, '')), '[^a-z0-9]+', ' ', 'g'))
$$;

-- Question-set digest of a template: lines "order_index US section US asked_as"
-- joined by RS, ordered by (order_index, asked_as COLLATE "C").
-- Mirrored by questionSetSha256() in app/lib/catalog-promotion/checks.ts.
CREATE OR REPLACE FUNCTION public.catalog_question_set_sha256(p_questions jsonb)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = pg_catalog, pg_temp
AS $$
  SELECT encode(sha256(convert_to(coalesce(string_agg(
           (q->>'order_index') || chr(31) || coalesce(q->>'section', '') || chr(31) || (q->>'asked_as'),
           chr(30) ORDER BY (q->>'order_index')::int, (q->>'asked_as') COLLATE "C"), ''), 'UTF8')), 'hex')
    FROM jsonb_array_elements(coalesce(p_questions, '[]'::jsonb)) q
$$;

