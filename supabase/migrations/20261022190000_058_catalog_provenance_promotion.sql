CREATE OR REPLACE FUNCTION public.catalog_transition_allowed(
  p_from public.catalog_candidate_state, p_to public.catalog_candidate_state)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT (p_from, p_to) IN (
           ('candidate'::public.catalog_candidate_state, 'extracted'::public.catalog_candidate_state),
           ('extracted', 'matched'), ('matched', 'verified'),
           ('verified', 'approved'), ('approved', 'published'))
      OR (p_to IN ('rejected', 'withdrawn')
          AND p_from IN ('candidate', 'extracted', 'matched', 'verified', 'approved'))
$$;

CREATE OR REPLACE FUNCTION public.guard_catalog_candidates()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'catalog_candidates are never deleted (withdraw or reject instead)' USING ERRCODE = '42501';
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NEW.state <> 'candidate' OR NEW.published_revision_id IS NOT NULL THEN
      RAISE EXCEPTION 'a new catalog candidate starts in state candidate' USING ERRCODE = '23514';
    END IF;
    NEW.submitted_at := now();
    NEW.updated_at := now();
    RETURN NEW;
  END IF;

  -- UPDATE
  IF NEW.id <> OLD.id OR NEW.submitted_at <> OLD.submitted_at
     OR (NEW.submitted_by IS DISTINCT FROM OLD.submitted_by AND NEW.submitted_by IS NOT NULL) THEN
    RAISE EXCEPTION 'candidate identity is immutable' USING ERRCODE = '42501';
  END IF;
  IF NEW.source_id IS DISTINCT FROM OLD.source_id AND OLD.source_id IS NOT NULL THEN
    RAISE EXCEPTION 'candidate source is immutable once set' USING ERRCODE = '42501';
  END IF;
  IF NEW.state IS DISTINCT FROM OLD.state AND NOT EXISTS (
       SELECT 1 FROM public.catalog_candidate_events e
        WHERE e.candidate_id = NEW.id AND e.from_state = OLD.state AND e.to_state = NEW.state
          AND e.tx_id = txid_current())
  THEN
    RAISE EXCEPTION 'candidate state changes only through catalog_candidate_events' USING ERRCODE = '42501';
  END IF;
  IF NEW.payload IS DISTINCT FROM OLD.payload AND OLD.state NOT IN ('candidate','extracted','matched') THEN
    RAISE EXCEPTION 'candidate payload is frozen from verified onward' USING ERRCODE = '42501';
  END IF;
  IF OLD.state IN ('published','rejected','withdrawn') AND (
       NEW.payload IS DISTINCT FROM OLD.payload OR NEW.checks IS DISTINCT FROM OLD.checks
    OR NEW.published_revision_id IS DISTINCT FROM OLD.published_revision_id
    OR NEW.state IS DISTINCT FROM OLD.state)
  THEN
    RAISE EXCEPTION 'candidate is in terminal state %', OLD.state USING ERRCODE = '42501';
  END IF;
  IF NEW.published_revision_id IS DISTINCT FROM OLD.published_revision_id
     AND (OLD.state <> 'approved' OR OLD.published_revision_id IS NOT NULL) THEN
    RAISE EXCEPTION 'published_revision_id is set once, by publish' USING ERRCODE = '42501';
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

