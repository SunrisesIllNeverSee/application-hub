-- Provenance columns are service-side; occurrence wording tied to a
-- revision or a canonical program never changes (any role).
CREATE OR REPLACE FUNCTION public.guard_program_questions_provenance()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NOT public.is_canonical_writer() AND (
       (TG_OP = 'INSERT' AND (NEW.source_id IS NOT NULL OR NEW.template_revision_id IS NOT NULL OR NEW.superseded_by_revision_id IS NOT NULL))
    OR (TG_OP = 'UPDATE' AND (NEW.source_id IS DISTINCT FROM OLD.source_id
                              OR NEW.template_revision_id IS DISTINCT FROM OLD.template_revision_id
                              OR NEW.superseded_by_revision_id IS DISTINCT FROM OLD.superseded_by_revision_id))
  ) THEN
    RAISE EXCEPTION 'program_questions provenance columns are service-side only' USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'UPDATE'
     AND NEW.asked_as IS DISTINCT FROM OLD.asked_as
     AND (OLD.template_revision_id IS NOT NULL OR public.is_canonical_program(OLD.program_id))
  THEN
    RAISE EXCEPTION 'published occurrence wording is immutable; publish a new template revision'
      USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.superseded_by_revision_id IS NOT NULL
     AND NEW.superseded_by_revision_id IS DISTINCT FROM OLD.superseded_by_revision_id THEN
    RAISE EXCEPTION 'a superseded occurrence cannot be reactivated' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS program_questions_provenance_guard ON public.program_questions;
CREATE TRIGGER program_questions_provenance_guard
  BEFORE INSERT OR UPDATE ON public.program_questions
  FOR EACH ROW EXECUTE FUNCTION public.guard_program_questions_provenance();

