-- Idempotent: returns the existing serial for (kind, target) or assigns the
-- next free digits-form serial (skipping any value already taken).
CREATE OR REPLACE FUNCTION public.catalog_assign_serial(p_kind text, p_target_id uuid)
RETURNS text
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  v_serial text;
  v_table  text;
  v_n      bigint;
  v_exists boolean;
BEGIN
  SELECT s.serial INTO v_serial FROM public.catalog_serials s
   WHERE s.kind = p_kind AND s.target_id = p_target_id;
  IF FOUND THEN RETURN v_serial; END IF;

  v_table := CASE p_kind WHEN 'EN' THEN 'catalog_entities' WHEN 'AP' THEN 'programs'
                         WHEN 'QU' THEN 'archived_questions' WHEN 'AQ' THEN 'program_questions' END;
  IF v_table IS NULL THEN
    RAISE EXCEPTION 'catalog_assign_serial: unknown kind %', p_kind USING ERRCODE = '22023';
  END IF;
  EXECUTE format('SELECT EXISTS (SELECT 1 FROM public.%I WHERE id = $1)', v_table)
     INTO v_exists USING p_target_id;
  IF NOT v_exists THEN
    RAISE EXCEPTION 'catalog_assign_serial: % target % not found', p_kind, p_target_id USING ERRCODE = '23503';
  END IF;

  LOOP
    v_n := nextval(format('public.catalog_serial_%s_seq', lower(p_kind))::regclass);
    v_serial := p_kind || '-' || lpad(v_n::text, greatest(4, length(v_n::text)), '0');
    INSERT INTO public.catalog_serials (serial, kind, target_table, target_id, origin)
    VALUES (v_serial, p_kind, v_table, p_target_id, 'assigned')
    ON CONFLICT (serial) DO NOTHING;
    IF FOUND THEN RETURN v_serial; END IF;
  END LOOP;
END;
$$;

